void Sala7ef_ElRenga() {
    ordered_set<string> os;
    map<string, ordered_multiset<string>> mp;

    int n; cin >> n;
    for (int i = 0;i < n;i++) {
        string s; cin >> s;
        string sorted = s;
        sort(sorted.begin(), sorted.end());
        os.insert(sorted);
        mp[sorted].insert(s);
    }

    int pre[(int)1e5 + 1] = {}, idx = 0;
    for (auto& str : os) {
        if (idx == 0) {
            pre[idx] = mp[str].size();
        }else {
            pre[idx] = pre[idx - 1] + mp[str].size();
        }
       idx++;
    }

    int q; cin >> q;
    while (q--) {
        string s; cin >> s;
        string sorted = s;
        sort(sorted.begin(), sorted.end());
        int index = os.order_of_key(sorted);
        if (index)
            index = pre[index - 1];
        index += mp[sorted].order_of_key(s + 'a');

        cout << index << '\n';
    }
}


